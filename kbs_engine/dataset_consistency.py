"""Informational consistency check of the KR-2 engine against the SYNTHETIC dataset.

Writes kbs_engine/reports/dataset_consistency.md.  The dataset was generated by this project from its
own assumptions; agreement with its labels is NOT a measure of real diagnostic accuracy.

    python -m kbs_engine.dataset_consistency
"""
from __future__ import annotations

from collections import Counter, defaultdict
from pathlib import Path

from . import dataset_cases as dc
from .engine import STATUS_ORDER, InferenceEngine
from .knowledge import KnowledgeBase

OUT = Path(__file__).resolve().parent / "reports" / "dataset_consistency.md"


def main():
    kb = KnowledgeBase()
    eng = InferenceEngine(kb)
    rows = [r for r in dc.load_rows() if r["Diagnostic_Status"] in ("Confirmed", "No Fault Detected")]
    reg = dc.load_register()
    stats = defaultdict(Counter)
    for row in rows:
        label = dc.LABEL_TO_KB[row["Fault_Type"]]
        r = eng.run(dc.case_from_row(row, reg, kb))
        s = stats[row["Fault_Type"]]
        s["n"] += 1
        s["outcome " + r["outcome"]] += 1
        if label.startswith("FLT"):
            h = next((h for h in r["faults"] if h["id"] == label), None)
            st = h["status"] if h else "none"
            if st in ("confirmed", "likely"):
                s["label fault likely+"] += 1
            if st in ("confirmed", "likely", "possible"):
                s["label fault possible+"] += 1
            if st == "pending":
                s["label fault pending"] += 1
            top = [x for x in r["faults"] if STATUS_ORDER.index(x["status"]) >= STATUS_ORDER.index("possible")]
            if top and top[0]["id"] == label:
                s["label fault ranked first"] += 1
        if r["safety"]:
            s["any safety message"] += 1
    cols = ["n", "label fault likely+", "label fault possible+", "label fault pending", "label fault ranked first",
            "outcome diagnosis", "outcome OUT-U", "outcome OUT-N", "any safety message"]
    L = ["# KR-2 engine vs synthetic dataset - consistency check (NOT accuracy)", "",
         "Records: Confirmed fault records and 'No Fault Detected' records from "
         "`data_preparation/data/interim/cleaned_pump_dataset.csv`.", "",
         "**Read this correctly:** the dataset and its labels were generated by this project from its own "
         "assumptions, using different symptom thresholds from the knowledge base and recording operator "
         "observations only ~85% of the time. Agreement or disagreement here shows how the engine behaves on "
         "realistic-looking inputs; it is **not** evidence of diagnostic accuracy on real pumps.", "",
         "Inputs: sensor columns become measurements (imputed values marked unknown); operator-recorded "
         "observed/trend symptoms become 'present'; observations not recorded stay 'unknown'; all pumps are "
         "assumed radial; no diagnostic test results are supplied (so nothing can be 'confirmed').", "",
         "| Label | " + " | ".join(cols) + " |", "|" + "---|" * (len(cols) + 1)]
    for label in sorted(stats):
        s = stats[label]
        cells = [str(s["n"])] + [f"{100 * s[c] / s['n']:.0f}%" for c in cols[1:]]
        if not dc.LABEL_TO_KB[label].startswith("FLT"):
            cells[1:5] = ["-"] * 4
        L.append(f"| {label} | " + " | ".join(cells) + " |")
    L += ["", "Typical reasons for low agreement (by design, not bugs):",
          "- No test results are available, so test-based rules (R-CAV-2, R-MIS-1, cause rules) cannot fire.",
          "- Many rules need operator observations that the synthetic records often omit; missing observations "
          "stay unknown, so rules remain pending instead of guessing.",
          "- The engine's provisional thresholds (e.g. vibration >= 6.0 mm/s) differ from the generator's.",
          "- Misalignment's only Strong-sourced route is the alignment test; its symptom rule is unvalidated."]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
